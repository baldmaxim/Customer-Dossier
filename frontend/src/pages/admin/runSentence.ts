// Итог разбора одной фразой — первая строка страницы разбора, ответ на «почему текста нет
// в карточках» без чтения частей текста и отпечатков.

import type { ItemState } from '../../api/types';
import type { IRunOutcome } from '../../components/admin/runOutcome';

/** Почему разобранное не перенесено — по судьбе найденного в тексте. */
const NOT_MOVED_REASON: Record<string, string> = {
  rejected_policy: 'источник был выключен в момент переноса — найденное перенесётся после его включения',
  rejected_stale: 'текст изменился после разбора — портал разберёт новую версию сам',
  superseded: 'его заменил более новый разбор того же текста',
  discarded: 'найденное отброшено',
};

const SENTENCES: Record<ItemState, string> = {
  in_cards: 'Сведения из этого текста перенесены в карточки компаний и объектов — у каждого есть цитата.',
  nothing_found: 'Текст о стройке, но связей между компаниями и объектами в нём не нашлось.',
  not_relevant: 'Модель не нашла в тексте строительной темы — в карточки такой текст не идёт.',
  built_not_in_cards: 'Текст разобран, но в карточки не перенесён.',
  queued: 'Разбор в очереди — портал выполнит его сам.',
  running: 'Разбор выполняется.',
  partial: 'Часть текста не разобрана — неполный разбор в карточки не идёт. Если повтор включён, портал повторит его сам.',
  failed: 'Разбор не удался. Если повтор включён, портал повторит его сам.',
  cancelled: 'Разбор отменён: источник выключили во время разбора. Такой разбор портал сам не повторяет.',
  no_policy: 'Источник выключен — пока его не включат, тексты модели не показываются.',
  no_run: 'Текст ещё не разбирался.',
};

export const outcomeSentence = (outcome: IRunOutcome, setStatus: string | null): string => {
  const reason = setStatus ? NOT_MOVED_REASON[setStatus] : undefined;
  if (outcome.state === 'built_not_in_cards' && reason) return `Текст разобран, но в карточки не перенесён: ${reason}.`;
  return SENTENCES[outcome.state];
};
