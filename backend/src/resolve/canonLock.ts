// Заведение и сопоставление компаний и объектов — по одной транзакции за раз (07.10.2026).
//
// Резолвер ищет компанию и объект по ключу имени без уникального индекса: два параллельных «найти или завести»
// одного нового имени заводили две карточки (интеграционный тест «полосы разбора»: четыре публикации — три
// компании). Каждый путь, который заводит компании и объекты или вешает на них реквизит, берёт эту блокировку
// первой командой своей транзакции: публикация разбора (reprocess/publish.ts), реестр ДОМ.РФ
// (registry/publish.ts), заведение по ИНН (companies/register.ts), назначение реквизита (companies/assignment.ts).
// Порядок везде один — сначала эта блокировка, потом блокировка реквизита: иначе взаимная блокировка.
// Резолвер берёт её ещё раз (повтор в той же транзакции ничего не стоит): новый путь, забывший про неё,
// не заведёт дубль. Держится до конца транзакции и действует на все процессы — API, CLI, работник ДОМ.РФ.

import type { DbExecutor } from '../db/pool.js';

export const CANON_LOCK_KEY = 'canon:entities';

export const lockCanonWrites = async (exec: DbExecutor): Promise<void> => {
  await exec.query('SELECT pg_advisory_xact_lock(hashtext($1))', [CANON_LOCK_KEY]);
};
