// Направление слияния по вердикту модели: к карточке, которую терять дороже. Название выжившей карточки
// становится названием компании, поэтому направление — это ещё и выбор имени.
//
// 06.10.2026: прежний вес решал числом написаний, и «Sminex» (163 доказательства, страница ДОМ.РФ) слился в
// «Смайнекс», у которого написаний было два («Смайнекс», «Смайнэкс»). Теперь по порядку: реквизиты, сведения
// ДОМ.РФ (у объекта — запись реестра, у компании — подтверждённая страница), действующие доказательства, более
// короткое название (в новостях имя стоит в падеже: «Инград», а не «Инграда»), число написаний.

export interface ICardWeight {
  identifiers: number;
  /** 1 — есть запись реестра (объект) или подтверждённая страница ДОМ.РФ (компания). */
  registry: number;
  /** Действующие доказательства утверждений с этой карточкой. */
  evidence: number;
  /** Длина названия со знаком минус: короче — весомее. */
  shortName: number;
  aliases: number;
}

const ORDER: ReadonlyArray<keyof ICardWeight> = ['identifiers', 'registry', 'evidence', 'shortName', 'aliases'];

/** a весомее b. Равенство — нет: направление остаётся таким, как пара стоит в очереди. */
export const heavierCard = (a: ICardWeight, b: ICardWeight): boolean => {
  for (const key of ORDER) if (a[key] !== b[key]) return a[key] > b[key];
  return false;
};

export const nameWeight = (name: string): number => -[...name.trim()].length;
