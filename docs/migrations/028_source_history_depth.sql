-- 028: глубина истории источника — за сколько дней назад собирать публикации.
--
-- NULL — прежнее поведение: Telegram-канал собирает только новое (первый запуск истории
-- не берёт), сайт со списком листает архив, пока его отдаёт пагинация.
-- Число — граница по дате публикации от «сейчас»: канал догружает историю назад до неё
-- (ограниченным числом страниц за проход, в прежнем темпе запросов), сайт перестаёт листать
-- архив, когда записи страницы старше границы. Лента RSS истории не даёт вовсе.
--
-- Колонка, а не ключ профиля: профиль сайта строгий и перезаписывается целиком командой
-- --site-profile, и глубина, заданная в админке, стиралась бы вместе с ним.

ALTER TABLE sources
  ADD COLUMN history_days INT
  CHECK (history_days IS NULL OR history_days BETWEEN 1 AND 3650);

COMMENT ON COLUMN sources.history_days IS
  'Глубина истории в днях от текущей даты; NULL — только новое (Telegram) / весь архив пагинации (сайт)';
